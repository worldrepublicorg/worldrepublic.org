DICTS_DIR = os.path.join(os.path.dirname(__file__), "..", "app", "[lang]", "dictionaries")


def main():
    for locale, trans in TRANSLATIONS.items():
        path = os.path.join(DICTS_DIR, f"{locale}.json")
        if not os.path.exists(path):
            print(f"Skip {locale} (file not found)")
            continue
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        # Update sections
        s = data["pages"]["wallet"]["sections"]
        s["security"] = trans["security"]
        s["google_account"] = trans["google_account"]
        s["google_not_linked"] = trans["google_not_linked"]
        s["passkeys"] = trans["passkeys"]
        s["passkeys_linked"] = trans["passkeys_linked"]
        # Update toasts.wallet
        w = data["toasts"]["wallet"]
        w["google_linked"] = trans["google_linked"]
        w["google_already_linked"] = trans["google_already_linked"]
        w["google_link_failed"] = trans["google_link_failed"]
        w["passkey_added"] = trans["passkey_added"]
        w["passkey_add_failed"] = trans["passkey_add_failed"]
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Updated {locale}")
    print("Done.")


if __name__ == "__main__":
    main()
