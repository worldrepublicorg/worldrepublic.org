// Verbose query logging is gated behind DEBUG_DB to keep build/runtime output quiet.
// Set DEBUG_DB=1 to re-enable per-query "starting"/"success" lines for local debugging.
const DEBUG_DB = process.env.DEBUG_DB === "1";

// Helper to generate party UUID
// Uses PostgreSQL's gen_random_uuid() via Drizzle's defaultRandom()
async function generatePartyId(): Promise<string> {
	// UUID is auto-generated by database default, but we need it for the insert
	// Import crypto for UUID generation
	const { randomUUID } = await import("node:crypto");
	return randomUUID();
}

// Helper to convert PostgreSQL party row to Party object
// Converts Date timestamps to number (milliseconds since epoch) for backward compatibility
// UUIDs are returned as strings (no conversion needed)
function pgRowToParty(row: {
	id: string; // UUID
	name: string;
	description: string | null;
	websiteUrl: string | null;
	foundedBy: string; // UUID
	leaderUsername: string;
	createdAt: Date;
	updatedAt: Date;
	dissolvedAt: Date | null;
}): Party {
	return {
		id: row.id, // UUID as string
		name: row.name,
		description: row.description || undefined,
		websiteUrl: row.websiteUrl || undefined,
		foundedBy: row.foundedBy, // UUID as string
		leaderUsername: row.leaderUsername,
		createdAt: row.createdAt.getTime(),
		updatedAt: row.updatedAt.getTime(),
	};
}

// Helper function to get user UUID from session
async function getUserUuidFromSession(): Promise<string> {
	const { auth } = await import("@/lib/auth");
	const session = await auth();

	if (!session?.user?.id) {
		throw new Error("Authentication required");
	}

	const authUserId = parseInt(String(session.user.id), 10);

	// Get UUID from users table
	const [user] = await db
		.select({ uuid: users.uuid })
		.from(users)
		.where(eq(users.id, authUserId))
		.limit(1);

	if (!user?.uuid) {
		throw new Error("User UUID not found");
	}

	return user.uuid;
}

// Party CRUD Operations

export async function createParty(
	data: CreatePartyData,
	pendingReferralCode?: string,
) {
	try {
		// Get UUID from session
		const userUuid = await getUserUuidFromSession();

		// Validation
		if (!data.name?.trim()) {
			return {
				success: false,
				error: "Name is required",
			};
		}

		// Check if user already founded a party and dissolve it if they have
		const [existingParty] = await db
			.select({ id: parties.id })
			.from(parties)
			.where(and(eq(parties.foundedBy, userUuid), isNull(parties.dissolvedAt)))
			.limit(1);

		if (existingParty) {
			// Dissolve the existing party before creating a new one
			await db
				.update(parties)
				.set({ dissolvedAt: new Date() })
				.where(eq(parties.id, existingParty.id));
		}

		// Ensure user profile exists (will be created if it doesn't)
		const profileResult = await getUserProfile(pendingReferralCode);
		if (!profileResult.success || !profileResult.profile?.username) {
			return {
				success: false,
				error: "User profile not found",
			};
		}

		const username = profileResult.profile.username;

		const partyId = await generatePartyId();
		const now = new Date();

		// Insert new party with denormalized leader username
		await db.insert(parties).values({
			id: partyId,
			name: data.name.trim(),
			description: data.description?.trim() || null,
			websiteUrl: data.websiteUrl?.trim() || undefined,
			foundedBy: userUuid,
			leaderUsername: username,
			createdAt: now,
			updatedAt: now,
			dissolvedAt: null,
		});

		// Revalidate paths and cache tags that show party/parties data.
		// New party affects parties list, ambassador leaderboard (referrer column),
		// and subsidy leaderboard (party row will appear when subsidies distribute).
		revalidatePath("/[lang]/govern", "page");
		revalidatePath("/[lang]/govern/parties/[id]", "page");
		revalidatePath("/[lang]/parties", "page");
		revalidatePath("/[lang]/parties/[id]", "page");
		revalidateTag("parties-list", "default");
		revalidateTag("ambassador-leaderboard", "default");
		revalidateTag("subsidy-leaderboard", "default");

		return { success: true, partyId };
	} catch (error) {
		console.error("Error creating party:", error);
		return {
			success: false,
			error: error instanceof Error ? error.message : "Failed to create party",
		};
	}
}

export async function getParty(partyId: string): Promise<Party | null> {
	const startTime = performance.now();
	const requestId = `req-${Date.now()}-${Math.random().toString(36).substring(7)}`;
	const QUERY_TIMEOUT_MS = 15000;

	try {
		// Execute query with timeout and retry logic
		const partyRow = await executeQueryWithTimeout(
			async (db) => {
				const [row] = await db
					.select(getTableColumns(parties))
					.from(parties)
					.where(eq(parties.id, partyId))
					.limit(1);
				return row;
			},
			requestId,
			QUERY_TIMEOUT_MS,
			"getParty",
		);

		if (!partyRow) {
			return null;
		}

		const party = pgRowToParty(partyRow);
		const duration = performance.now() - startTime;

		if (duration > 1000) {
			console.warn(
				`[getParty] Slow query detected: ${duration.toFixed(2)}ms (requestId: ${requestId}, partyId: ${partyId})`,
			);
		}

		return party;
	} catch (error) {
		const duration = performance.now() - startTime;
		const { getConnectionInfo, checkConnectionHealth } = await import(
			"@/lib/db/connection"
		);
		const connInfo = getConnectionInfo();

		// Check connection health when we get a timeout
		let healthCheck: {
			healthy: boolean;
			latency?: number;
			error?: string;
		} | null = null;
		if (
			error instanceof Error &&
			(error.message.includes("timeout") || error.message.includes("hanging"))
		) {
			try {
				healthCheck = await Promise.race([
					checkConnectionHealth(),
					new Promise<{ healthy: boolean; error: string }>((resolve) =>
						setTimeout(
							() => resolve({ healthy: false, error: "Health check timeout" }),
							2000,
						),
					),
				]);
			} catch (healthError) {
				healthCheck = {
					healthy: false,
					error:
						healthError instanceof Error
							? healthError.message
							: String(healthError),
				};
			}
		}

		const errorDetails = {
			requestId,
			partyId,
			duration: `${duration.toFixed(2)}ms`,
			errorType: error instanceof Error ? error.constructor.name : typeof error,
			errorMessage: error instanceof Error ? error.message : String(error),
			errorStack: error instanceof Error ? error.stack : undefined,
			connectionInfo: connInfo,
			healthCheck,
			timestamp: new Date().toISOString(),
		};

		console.error(
			`[getParty] Error getting party ${partyId} after ${duration.toFixed(2)}ms (requestId: ${requestId}):`,
			JSON.stringify(errorDetails, null, 2),
		);
		console.error("[getParty] Raw error:", error);

		return null;
	}
}

export async function updateParty(
	partyId: string,
	data: UpdatePartyData,
): Promise<{ success: boolean; error?: string }> {
	try {
		// Get UUID from session
		const userUuid = await getUserUuidFromSession();

		// Get party to verify ownership
		const party = await getParty(partyId);
		if (!party) {
			return { success: false, error: "Party not found" };
		}

		if (party.foundedBy !== userUuid) {
			return {
				success: false,
				error: "Only the party founder can update the party",
			};
		}

		const pgUpdates: {
			name?: string;
			description?: string | null;
			websiteUrl?: string | null;
			updatedAt: Date;
		} = {
			updatedAt: new Date(),
		};

		if (data.name !== undefined) {
			if (!data.name.trim()) {
				return { success: false, error: "Name cannot be empty" };
			}
			pgUpdates.name = data.name.trim();
		}

		if (data.description !== undefined) {
			pgUpdates.description = data.description.trim() || null;
		}

		if (data.websiteUrl !== undefined) {
			pgUpdates.websiteUrl = data.websiteUrl.trim() || null;
		}

		await db.update(parties).set(pgUpdates).where(eq(parties.id, partyId));

		// Party name appears in subsidy leaderboard, so bust it too if the name changed.
		revalidatePath("/[lang]/govern", "page");
		revalidatePath("/[lang]/govern/parties/[id]", "page");
		revalidatePath("/[lang]/parties", "page");
		revalidatePath(`/[lang]/parties/${partyId}`, "page");
		revalidateTag("parties-list", "default");
		revalidateTag("subsidy-leaderboard", "default");

		return { success: true };
	} catch (error) {
		console.error("Error updating party:", error);
		return {
			success: false,
			error: error instanceof Error ? error.message : "Failed to update party",
		};
	}
}

export async function deleteParty(
	partyId: string,
): Promise<{ success: boolean; error?: string }> {
	try {
		// Get UUID from session
		const userUuid = await getUserUuidFromSession();

		const party = await getParty(partyId);
		if (!party) {
			return { success: false, error: "Party not found" };
		}

		if (party.foundedBy !== userUuid) {
			return {
				success: false,
				error: "Only the party founder can dissolve the party",
			};
		}

		// Set dissolvedAt timestamp (soft delete)
		await db
			.update(parties)
			.set({ dissolvedAt: new Date() })
			.where(eq(parties.id, partyId));

		revalidatePath("/[lang]/govern", "page");
		revalidatePath("/[lang]/govern/parties/[id]", "page");
		revalidatePath("/[lang]/parties", "page");
		revalidatePath("/[lang]/parties/[id]", "page");
		revalidateTag("parties-list", "default");
		revalidateTag("ambassador-leaderboard", "default");
		revalidateTag("subsidy-leaderboard", "default");

		return { success: true };
	} catch (error) {
		console.error("Error deleting party:", error);
		return {
			success: false,
			error:
				error instanceof Error ? error.message : "Failed to dissolve party",
		};
	}
}

// Retry utility for transient network errors
async function withRetry<T>(
	fn: () => Promise<T>,
	options: {
		maxRetries?: number;
		initialDelay?: number;
		maxDelay?: number;
		retryableErrors?: string[];
		context?: string;
	} = {},
): Promise<T> {
	const {
		maxRetries = 5,
		initialDelay = 500,
		maxDelay = 8000,
		retryableErrors = [
			"ECONNRESET",
			"ETIMEDOUT",
			"ENOTFOUND",
			"ECONNREFUSED",
			"timeout",
			"fetch failed",
			"network",
			"connection",
		],
		context = "query",
	} = options;

	let lastError: unknown;
	let delay = initialDelay;

	for (let attempt = 0; attempt <= maxRetries; attempt++) {
		try {
			const attemptStart = performance.now();
			const result = await fn();
			const attemptDuration = performance.now() - attemptStart;
			if (attemptDuration > 1000) {
				console.warn(
					`[${context}] Slow attempt: ${attemptDuration.toFixed(2)}ms (attempt ${attempt + 1})`,
				);
			}
			return result;
		} catch (error) {
			lastError = error;
			const errorMessage =
				error instanceof Error ? error.message : String(error);
			const errorString = errorMessage.toLowerCase();

			// Check if error is retryable
			const isRetryable = retryableErrors.some((pattern) =>
				errorString.includes(pattern.toLowerCase()),
			);

			// Don't retry on last attempt or if error is not retryable
			if (attempt === maxRetries || !isRetryable) {
				throw error;
			}

			// Log retry attempt
			console.warn(
				`[${context}] Retry attempt ${attempt + 1}/${maxRetries} after ${delay}ms. Error: ${errorMessage.substring(0, 100)}`,
			);

			// Wait before retrying (exponential backoff with jitter)
			await new Promise((resolve) =>
				setTimeout(resolve, delay + Math.random() * 100),
			);
			delay = Math.min(delay * 2, maxDelay);
		}
	}

	throw lastError;
}

// Execute query with timeout and retry logic
async function executeQueryWithTimeout<T>(
	queryFn: (db: ReturnType<typeof getDbReadOnly>) => Promise<T>,
	requestId: string,
	timeoutMs: number = 15000,
	context: string = "getParties",
): Promise<T> {
	const { getDbReadOnly, getConnectionInfo } = await import(
		"@/lib/db/connection"
	);
	const connInfo = getConnectionInfo();
	const readDb = getDbReadOnly();

	if (DEBUG_DB) {
		console.log(
			`[${context}] Starting query (requestId: ${requestId}, connection: ${connInfo.connectionType}, timeout: ${timeoutMs}ms)`,
		);
	}

	const startTime = performance.now();
	const result = await Promise.race([
		withRetry(async () => queryFn(readDb), {
			maxRetries: 2, // Reduced retries since we have shorter timeout
			initialDelay: 300,
			maxDelay: 1500,
			context: `${context}-${requestId}`,
		}),
		new Promise<never>((_, reject) => {
			setTimeout(
				() =>
					reject(
						new Error(
							`Query timeout after ${timeoutMs}ms - Neon HTTP driver may be hanging`,
						),
					),
				timeoutMs,
			);
		}),
	]);
	const duration = performance.now() - startTime;
	if (duration > 2000) {
		console.warn(
			`[${context}] Slow query: ${duration.toFixed(2)}ms (requestId: ${requestId})`,
		);
	}
	return result;
}

// Party Discovery

export async function getParties(
	filters?: PartyFilters,
): Promise<Party[] | null> {
	const startTime = performance.now();
	const requestId = `req-${Date.now()}-${Math.random().toString(36).substring(7)}`;
	const QUERY_TIMEOUT_MS = 15000;

	try {
		const limit = filters?.limit || 1000;
		const offset = filters?.offset || 0;

		// Build query conditions
		let whereCondition = isNull(parties.dissolvedAt); // Only active parties

		// Add search filter if provided
		if (filters?.search) {
			const searchPattern = `%${filters.search}%`;
			const searchClause = or(
				ilike(parties.name, searchPattern),
				ilike(parties.description, searchPattern),
				ilike(parties.leaderUsername, searchPattern),
			);
			if (searchClause) {
				const combined = and(whereCondition, searchClause);
				if (combined === undefined) {
					throw new Error("Failed to build party search filter");
				}
				whereCondition = combined;
			}
		}

		const orderClause =
			filters?.order === "random" ? sql`random()` : desc(parties.createdAt);

		// Execute query with timeout and retry logic
		const queryStartTime = performance.now();
		const partyRows = await executeQueryWithTimeout(
			async (db) => {
				return await db
					.select(getTableColumns(parties))
					.from(parties)
					.where(whereCondition)
					.orderBy(orderClause)
					.limit(limit)
					.offset(offset);
			},
			requestId,
			QUERY_TIMEOUT_MS,
			"getParties",
		);

		const queryDuration = performance.now() - queryStartTime;
		const totalDuration = performance.now() - startTime;

		// Log successful query with timing
		if (queryDuration > 1000) {
			const { getConnectionInfo } = await import("@/lib/db/connection");
			const connInfo = getConnectionInfo();
			console.warn(
				`[getParties] Slow query detected: ${queryDuration.toFixed(2)}ms (requestId: ${requestId}, limit: ${limit}, offset: ${offset}, connection: ${connInfo.connectionType})`,
			);
		}

		// Convert PostgreSQL rows to Party objects
		const result = partyRows.map(pgRowToParty);

		if (DEBUG_DB) {
			console.log(
				`[getParties] Success: ${result.length} parties in ${totalDuration.toFixed(2)}ms (requestId: ${requestId})`,
			);
		}

		return result;
	} catch (error) {
		const totalDuration = performance.now() - startTime;
		const { getConnectionInfo, checkConnectionHealth } = await import(
			"@/lib/db/connection"
		);
		const connInfo = getConnectionInfo();

		// Check connection health when we get a timeout
		let healthCheck: {
			healthy: boolean;
			latency?: number;
			error?: string;
		} | null = null;
		if (
			error instanceof Error &&
			(error.message.includes("timeout") || error.message.includes("hanging"))
		) {
			try {
				healthCheck = await Promise.race([
					checkConnectionHealth(),
					new Promise<{ healthy: boolean; error: string }>((resolve) =>
						setTimeout(
							() => resolve({ healthy: false, error: "Health check timeout" }),
							2000,
						),
					),
				]);
			} catch (healthError) {
				healthCheck = {
					healthy: false,
					error:
						healthError instanceof Error
							? healthError.message
							: String(healthError),
				};
			}
		}

		const errorDetails = {
			requestId,
			duration: `${totalDuration.toFixed(2)}ms`,
			errorType: error instanceof Error ? error.constructor.name : typeof error,
			errorMessage: error instanceof Error ? error.message : String(error),
			errorStack: error instanceof Error ? error.stack : undefined,
			filters: {
				limit: filters?.limit,
				offset: filters?.offset,
				hasSearch: !!filters?.search,
			},
			connectionInfo: connInfo,
			healthCheck,
			timestamp: new Date().toISOString(),
		};

		// Enhanced error logging with structured data
		console.error(
			`[getParties] Error after ${totalDuration.toFixed(2)}ms (requestId: ${requestId}):`,
			JSON.stringify(errorDetails, null, 2),
		);

		// Also log the raw error for stack traces
		console.error("[getParties] Raw error:", error);

		return null;
	}
}

// User Party Operations

export async function getUserParty(): Promise<Party | null> {
	try {
		// Get UUID from session
		const userUuid = await getUserUuidFromSession();
		const readDb = getDbReadOnly();

		const [partyRow] = await readDb
			.select(getTableColumns(parties))
			.from(parties)
			.where(and(eq(parties.foundedBy, userUuid), isNull(parties.dissolvedAt)))
			.limit(1);

		if (!partyRow) {
			return null;
		}

		return pgRowToParty(partyRow);
	} catch (error) {
		console.error("Error getting user party:", error);
		return null;
	}
}
